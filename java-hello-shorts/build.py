def wrap(lines):
    """Statements shown alone run inside main of the program above."""
    return "\n".join(HELLO[:2] + ["    " + l for l in lines] + HELLO[3:])

def run(src, fname="Main.java"):
    """(stdout, None) if it compiles and runs, (None, javac's first error message) otherwise."""
    d = tempfile.mkdtemp(dir=TMP)
    open(os.path.join(d, fname), "w").write(src)
    c = subprocess.run(["javac", "-J-Duser.language=en", fname], cwd=d, capture_output=True, text=True)
    if c.returncode:
        return None, re.search(r"error: (.*)", c.stderr).group(1)
    r = subprocess.run(["java", "-cp", d, "Main"], capture_output=True, text=True, check=True)
    return r.stdout, None

def check(sid, src, expect=None, error=None, fname="Main.java"):
    out, err = run(src, fname)
    if error is not None:
        if err is None or error not in err:
            raise ValueError(f"{sid}: expected compile error {error!r}, got {err!r} / output {out!r}")
    elif out != expect:
        raise ValueError(f"{sid}: prints {out!r}, but the script expects {expect!r} ({err or 'no error'})")
    EXAMPLES.append((sid, fname, src, out, err))
    return out, err

def jcode(sid, lines, expect, mark=(), full=False, sm=False):
    """Code block; the program (or the statements, run inside main) must print `expect`."""
    LAST["out"], _ = check(sid, "\n".join(lines) if full else wrap(lines), expect)
    return code(lines, mark, sm)

def jerr(sid, lines, *errors, mark=None):
    """Code block whose every line is its own broken statement; line k must fail with errors[k]."""
    LAST["err"] = [check(sid, wrap([l]), error=e)[1] for l, e in zip(lines, errors, strict=True)]
    return code(lines, range(len(lines)) if mark is None else mark)

def term(cmds=(), label="실행 결과"):
    """Console box: optional shell commands, then what the last jcode() printed."""
    body = "".join(f'<div class="cmd">$ {html.escape(c)}</div>' for c in cmds)
    body += "".join(f"<div>{html.escape(l) or '&nbsp;'}</div>" for l in LAST["out"].rstrip("\n").split("\n"))
    return f'<div class="term in"><i>{label}</i>{body}</div>'

def err():
    """javac's messages for the last jerr() block."""
    return '<div class="term err in"><i>컴파일 오류</i>' + "".join(f"<div>error: {html.escape(e)}</div>" for e in LAST["err"]) + "</div>"

